"""Draw the Legendre-symbol table using only the Python standard library.

Regenerate the adjacent SVG from any working directory with:
    python path/to/quad_residue.py

The layout and palette follow quad_residue.png. Values are calculated using
Euler's criterion instead of being transcribed from the raster image.
"""

from math import isqrt
from pathlib import Path


PRIMES = tuple(
    p for p in range(3, 128, 2) if all(p % d for d in range(3, isqrt(p) + 1, 2))
)
COLUMNS = 30
WIDTH = 902
LABEL_WIDTH = 49
HEADER_HEIGHT = 35
ROW_HEIGHT = 29
CELL_WIDTH = (WIDTH - LABEL_WIDTH) / COLUMNS
HEIGHT = HEADER_HEIGHT + ROW_HEIGHT * len(PRIMES)
COLORS = {1: "#ffaaff", -1: "#aaffff", 0: "#ffffaa"}


def legendre(a: int, p: int) -> int:
    """Return (a/p), for an odd prime p, including zero when p divides a."""
    value = pow(a, (p - 1) // 2, p)
    return -1 if value == p - 1 else value


def draw() -> str:
    """Return a self-contained SVG with editable vector shapes and text."""
    svg = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!-- Generated by quad_residue.py; edit the script to regenerate. -->",
        '<svg xmlns="http://www.w3.org/2000/svg"'
        f' width="{WIDTH + 1}" height="{HEIGHT + 1}"'
        f' viewBox="-0.5 -0.5 {WIDTH + 1} {HEIGHT + 1}"'
        ' role="img" aria-labelledby="title description">',
        '  <title id="title">Table of Legendre symbols</title>',
        '  <desc id="description">Columns give a from 1 to 30; rows give the odd',
        "    primes p from 3 to 127. Each entry is the Legendre symbol (a/p).",
        "    Pink cells contain 1 (quadratic residues), cyan cells contain",
        "    minus 1 (nonresidues), and yellow cells contain 0 (p divides a).</desc>",
        "  <style>",
        '    text { font-family: "Times New Roman", "Liberation Serif", serif;',
        "           font-size: 14px; fill: #202122; text-anchor: middle; }",
        "    .header { font-weight: bold; }",
        "    .axis { font-size: 16px; font-style: italic; font-weight: bold; }",
        "  </style>",
        f'  <rect width="{WIDTH}" height="{HEIGHT}" fill="#eaecf0"/>',
        '  <g id="cells" shape-rendering="crispEdges">',
    ]

    for row, p in enumerate(PRIMES):
        y = HEADER_HEIGHT + row * ROW_HEIGHT
        for a in range(1, COLUMNS + 1):
            x = LABEL_WIDTH + (a - 1) * CELL_WIDTH
            color = COLORS[legendre(a, p)]
            svg.append(
                f'    <rect x="{x:.3f}" y="{y}" width="{CELL_WIDTH:.3f}"'
                f' height="{ROW_HEIGHT}" fill="{color}"/>'
            )
    svg.append("  </g>")

    grid = [f"M0 0H{WIDTH}V{HEIGHT}H0Z"]
    for column in range(COLUMNS):
        x = LABEL_WIDTH + column * CELL_WIDTH
        grid.append(f"M{x:.3f} 0V{HEIGHT}")
    for row in range(len(PRIMES)):
        y = HEADER_HEIGHT + row * ROW_HEIGHT
        grid.append(f"M0 {y}H{WIDTH}")
    svg.extend(
        [
            f'  <path d="{" ".join(grid)}" fill="none" stroke="#a2a9b1"'
            ' stroke-width="1" shape-rendering="crispEdges"/>',
            f'  <path d="M0 0L{LABEL_WIDTH} {HEADER_HEIGHT}" fill="none"'
            ' stroke="#a2a9b1" stroke-width="0.7" stroke-dasharray="1 1"/>',
            '  <text class="axis" x="11" y="30">p</text>',
            '  <text class="axis" x="40" y="16">a</text>',
            '  <g class="header">',
        ]
    )
    for a in range(1, COLUMNS + 1):
        x = LABEL_WIDTH + (a - 0.5) * CELL_WIDTH
        svg.append(f'    <text x="{x:.3f}" y="24">{a}</text>')
    for row, p in enumerate(PRIMES):
        y = HEADER_HEIGHT + (row + 0.5) * ROW_HEIGHT + 5
        svg.append(f'    <text x="{LABEL_WIDTH / 2}" y="{y}">{p}</text>')
    svg.extend(["  </g>", '  <g id="values">'])
    for row, p in enumerate(PRIMES):
        y = HEADER_HEIGHT + (row + 0.5) * ROW_HEIGHT + 5
        for a in range(1, COLUMNS + 1):
            x = LABEL_WIDTH + (a - 0.5) * CELL_WIDTH
            value = str(legendre(a, p)).replace("-", "\N{MINUS SIGN}")
            svg.append(f'    <text x="{x:.3f}" y="{y}">{value}</text>')
    svg.extend(["  </g>", "</svg>", ""])
    return "\n".join(svg)


if __name__ == "__main__":
    output = Path(__file__).with_suffix(".svg")
    output.write_text(draw(), encoding="utf-8", newline="\n")
    print(f"Wrote {output}")
